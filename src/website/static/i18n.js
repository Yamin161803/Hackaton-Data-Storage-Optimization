const LOCALES = { en: "en-US", sv: "sv-SE" };

let LANG = (() => {
  try { const saved = localStorage.getItem("lang"); if (saved in TEXT) return saved; } catch (e) {}
  return "en";
})();

/** Text for `key` in the current language, with {name} placeholders filled from `vars`. */
function t(key, vars = {}) {
  const entry = TEXT[LANG][key] ?? TEXT.en[key];
  if (entry === undefined) return key;
  if (typeof entry === "function") return entry(vars);
  return entry.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

/** A number in the current language, e.g. 1234.5 -> "1,234.5" (en) or "1 234,5" (sv). */
function fmtLocal(n, decimals = 0) {
  return Number(n || 0).toLocaleString(LOCALES[LANG],
    { minimumFractionDigits: decimals, maximumFractionDigits: decimals });
}

/** Fill in every data-i18n / data-i18n-attr element and mark the active language. */
function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-attr]").forEach(el => {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":").map(s => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
  document.querySelectorAll("[data-lang]").forEach(b =>
    b.setAttribute("aria-pressed", String(b.dataset.lang === LANG)));
}

function setLang(lang) {
  if (!(lang in TEXT) || lang === LANG) return;
  LANG = lang;
  try { localStorage.setItem("lang", lang); } catch (e) {}
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
}

document.querySelectorAll("[data-lang]").forEach(b =>
  b.addEventListener("click", () => setLang(b.dataset.lang)));
