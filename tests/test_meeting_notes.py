def make_split_dir(root: Path, frame_times, transcript: str) -> Path:
    split = root / "My_talk_split"
    frames = split / "frames"
    frames.mkdir(parents=True)
    rows = ["frame,seconds,timestamp,file,reason,change"]
    for i, t in enumerate(frame_times, start=1):
        name = f"frame_{i}.jpg"
        (frames / name).write_bytes(b"jpg")
        rows.append(f"{i},{t:.3f},x,{name},change,0.1")
    (frames / "timestamps.csv").write_text("\n".join(rows) + "\n", encoding="utf-8")
    (split / "audio.txt").write_text(transcript, encoding="utf-8")
    return split


TRANSCRIPT = """\
[   0.00 ->    4.00] Hello and welcome.
[   4.00 ->    9.50] This is the intro.
[  10.00 ->   14.00] Now the second slide.
[  14.00 ->   20.00] More about it.
[  30.00 ->   35.00] Last words.
"""


def test_segments_go_under_the_frame_showing_when_they_start(tmp_path):
    split = make_split_dir(tmp_path, [0, 10, 25], TRANSCRIPT)
    md = build_notes(split).read_text(encoding="utf-8")
    one, two, three = md.split("## 1.")[1], md.split("## 2.")[1], md.split("## 3.")[1]
    assert "Hello and welcome. This is the intro." in one.split("## 2.")[0]
    assert "Now the second slide. More about it." in two.split("## 3.")[0]
    assert "Last words." in three
    assert "Now the second" not in one.split("## 2.")[0]


def test_output_layout(tmp_path):
    split = make_split_dir(tmp_path, [0, 10, 25], TRANSCRIPT)
    md_path = build_notes(split)
    assert md_path == split / "notes.md"
    md = md_path.read_text(encoding="utf-8")
    assert md.startswith("# My talk\n")
    assert "3 frames · 00:00:35 long" in md
    assert "## 2. 00:00:10 – 00:00:25" in md
    assert "## 3. 00:00:25 – 00:00:35" in md
    assert "![Frame at 00:00:10](frames/frame_2.jpg)" in md
    assert "Contents" not in md and "#frame-" not in md


def test_segment_crossing_a_frame_change_goes_where_most_of_it_is(tmp_path):
    transcript = ("[   0.00 ->    3.00] Before.\n"
                  "[   3.00 ->   12.00] Mostly on slide two.\n"   # 2 s on frame 1, 7 s on frame 2
                  "[  12.00 ->   16.00] Mostly still slide two.\n")  # 3 s on frame 2, 1 s on frame 3
    split = make_split_dir(tmp_path, [0, 5, 15], transcript)
    md = build_notes(split).read_text(encoding="utf-8")
    one = md.split("## 1.")[1].split("## 2.")[0]
    two = md.split("## 2.")[1].split("## 3.")[0]
    assert "Before." in one and "slide two" not in one
    assert "Mostly on slide two. Mostly still slide two." in two


def test_frame_without_speech(tmp_path):
    split = make_split_dir(tmp_path, [0, 22, 25], TRANSCRIPT)
    md = build_notes(split).read_text(encoding="utf-8")
    assert md.split("## 2.")[1].split("## 3.")[0].count("_(no speech)_") == 1


def test_links_work_from_another_folder(tmp_path):
    split = make_split_dir(tmp_path, [0], TRANSCRIPT)
    md = build_notes(split, output=tmp_path / "notes (draft)" / "talk.md", title="T")
    text = md.read_text(encoding="utf-8")
    assert "](../My_talk_split/frames/frame_1.jpg)" in text


def test_paths_with_parentheses_are_escaped(tmp_path):
    split = make_split_dir(tmp_path / "a (b)", [0], TRANSCRIPT)
    md = build_notes(split, output=tmp_path / "out.md")
    assert "](a%20%28b%29/My_talk_split/frames/frame_1.jpg)" in md.read_text(encoding="utf-8")


