import io  # noqa: E402
import json  # noqa: E402
import urllib.error  # noqa: E402

import summarize as summarize_mod  # noqa: E402
from summarize import Summary, SummaryError, summarize  # noqa: E402


def test_summary_is_written_at_the_top(tmp_path):
    split = make_split_dir(tmp_path, [0, 10, 25], TRANSCRIPT)
    seen = []

    def fake(text):
        seen.append(text)
        return Summary("A short talk.", ["Point one", "Point two"], "fake-model")

    md = build_notes(split, summarizer=fake).read_text(encoding="utf-8")
    assert seen == ["Hello and welcome. This is the intro. Now the second slide. "
                    "More about it. Last words."]
    assert md.index("## Summary") < md.index("## 1.")
    assert "## Summary\n\nA short talk.\n\n### Key points\n\n- Point one\n- Point two\n" in md
    assert "generated by fake-model" in md


def test_no_summary_by_default_in_build_notes(tmp_path):
    split = make_split_dir(tmp_path, [0], TRANSCRIPT)
    assert "## Summary" not in build_notes(split).read_text(encoding="utf-8")


def fake_ollama(monkeypatch, content=None, error=None):
    requests = []

    def urlopen(req, timeout=None):
        requests.append(json.loads(req.data))
        if error:
            raise error
        return io.BytesIO(json.dumps({"message": {"content": content}}).encode())

    monkeypatch.setattr(summarize_mod.urllib.request, "urlopen", urlopen)
    return requests


def test_summarize_parses_ollama_json(monkeypatch):
    reply = '<think>hmm</think>{"overview": "About X.", "key_points": ["a", " ", "b"]}'
    requests = fake_ollama(monkeypatch, reply)
    s = summarize("some words", model="m", hint="Say GraalVM")
    assert (s.overview, s.key_points, s.model) == ("About X.", ["a", "b"], "m")
    assert requests[0]["model"] == "m"
    assert "Say GraalVM" in requests[0]["messages"][0]["content"]


def test_long_transcript_is_summarized_in_parts(monkeypatch):
    requests = fake_ollama(monkeypatch, '{"overview": "o", "key_points": ["k"]}')
    monkeypatch.setattr(summarize_mod, "CHUNK_WORDS", 3)
    summarize("one two three four five six seven")   # 3 parts + 1 combine
    assert len(requests) == 4
    assert "part 1 of 3" in requests[0]["messages"][1]["content"]
    assert "Combine them" in requests[-1]["messages"][1]["content"]


def test_summarize_errors(monkeypatch):
    fake_ollama(monkeypatch, error=urllib.error.HTTPError("u", 404, "nf", {}, None))
    with pytest.raises(SummaryError, match="ollama pull m"):
        summarize("words", model="m")
    fake_ollama(monkeypatch, error=urllib.error.URLError("refused"))
    with pytest.raises(SummaryError, match="Is Ollama running"):
        summarize("words")
    fake_ollama(monkeypatch, "not json")
    with pytest.raises(SummaryError, match="expected JSON"):
        summarize("words")
    with pytest.raises(SummaryError, match="empty"):
        summarize("   ")


def test_embedded_images_need_no_image_files(tmp_path):
    split = make_split_dir(tmp_path, [0], TRANSCRIPT)
    md = build_notes(split, output=tmp_path / "talk.md", embed_images=True)
    text = md.read_text(encoding="utf-8")
    assert "![Frame at 00:00:00](data:image/jpeg;base64,anBn)" in text  # b"jpg"
    assert "frames/" not in text
