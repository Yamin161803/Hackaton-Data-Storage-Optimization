def test_summary_is_written_at_the_top(tmp_path):
    split = make_split_dir(tmp_path, [0, 10, 25], TRANSCRIPT)
    seen = []

    def fake(text):
        seen.append(text)
        return Summary("A short talk.", ["Point one", "Point two"], "fake-model")

    md = build_notes(split, summarizer=fake).read_text(encoding="utf-8")
    assert seen == ["Hello and welcome. This is the intro. Now the second slide. "
                    "More about it. Last words."]
    assert md.index("## Summary") < md.index("## 1.")
    assert "## Summary\n\nA short talk.\n\n### Key points\n\n- Point one\n- Point two\n" in md
    assert "generated by fake-model" in md


